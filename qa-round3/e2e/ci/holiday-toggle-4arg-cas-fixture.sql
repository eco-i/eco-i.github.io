-- SYNTHETIC CI-ONLY holiday toggle versioned CAS. Never apply to any live DB.
-- Non-production QA fixture with invented staff IDs 1,2,3.
\set ON_ERROR_STOP on
BEGIN;
CREATE TABLE public.qa_holiday_toggle_state (
 employee_id smallint PRIMARY KEY CHECK(employee_id IN (1,2,3)),
 holiday_work_enabled boolean NOT NULL DEFAULT false,
 eligibility_revision bigint NOT NULL DEFAULT 0 CHECK(eligibility_revision >= 0)
);
INSERT INTO public.qa_holiday_toggle_state(employee_id) VALUES (1),(2),(3);
CREATE TABLE public.qa_holiday_toggle_audit (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 employee_id smallint NOT NULL REFERENCES public.qa_holiday_toggle_state(employee_id),
 enabled boolean NOT NULL,
 revision bigint NOT NULL,
 actor smallint NOT NULL CHECK(actor IN (1,3))
);
CREATE FUNCTION public.qa_holiday_toggle_cas(
 p_token uuid,p_employee_id smallint,p_enabled boolean,p_expected_revision bigint
) RETURNS boolean LANGUAGE plpgsql AS $QA$
DECLARE v boolean; rev bigint; actor smallint;
BEGIN
 IF p_token='11111111-1111-4111-8111-111111111111'::uuid THEN actor:=1;
 ELSIF p_token='33333333-3333-4333-8333-333333333333'::uuid THEN actor:=3;
 ELSE RAISE EXCEPTION 'QA_ADMIN_TOKEN_DENIED'; END IF;
 IF p_employee_id<>2 OR p_enabled IS NULL OR p_expected_revision IS NULL
    OR p_expected_revision<0 THEN RAISE EXCEPTION 'QA_HOLIDAY_BAD_ARGS'; END IF;
 SELECT holiday_work_enabled,eligibility_revision INTO v,rev
 FROM public.qa_holiday_toggle_state WHERE employee_id=p_employee_id FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'QA_HOLIDAY_TARGET_NOT_FOUND'; END IF;
 IF rev<>p_expected_revision THEN RAISE EXCEPTION 'STALE_HOLIDAY_ELIGIBILITY'; END IF;
 IF v=p_enabled THEN RETURN true; END IF;
 UPDATE public.qa_holiday_toggle_state
 SET holiday_work_enabled=p_enabled, eligibility_revision=rev+1
 WHERE employee_id=p_employee_id;
 INSERT INTO public.qa_holiday_toggle_audit(employee_id,enabled,revision,actor)
 VALUES(p_employee_id,p_enabled,rev+1,actor);
 RETURN true;
END $QA$;
COMMIT;
