CREATE FUNCTION public._is_holiday_work_day(p_day date) RETURNS boolean
LANGUAGE sql STABLE AS $$ SELECT EXISTS(
  SELECT 1 FROM public.maintenance_schedule_state m,
    LATERAL jsonb_array_elements(m.data->'holidays') h
  WHERE m.id=1 AND h->>'date'=p_day::text
) $$;
