BEGIN;
CREATE TABLE public.qa_two_admin_shared_revision (
 id smallint PRIMARY KEY CHECK (id=1),
 revision bigint NOT NULL DEFAULT 0,
 target_status text NOT NULL DEFAULT 'active'
   CHECK (target_status IN ('active','readonly','disabled'))
);
INSERT INTO public.qa_two_admin_shared_revision (id) VALUES (1);
CREATE TABLE public.qa_two_admin_account_events (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 employee_id smallint NOT NULL CHECK (employee_id=2),
 account_status text NOT NULL CHECK (account_status IN ('active','readonly','disabled')),
 effective_date date NOT NULL,
 note text NOT NULL DEFAULT '',
 created_at timestamptz NOT NULL DEFAULT now(),
 created_by smallint NOT NULL CHECK (created_by IN (1,3))
);
-- Artificial row-level transaction/CAS behavior independent of production migration.
CREATE FUNCTION public.qa_two_admin_change_account(
 p_actor_token uuid,p_target_id smallint,p_status text,p_effective_date date,
 p_note text,p_expected jsonb,p_expected_revision text
) RETURNS boolean LANGUAGE plpgsql AS $QA$
DECLARE current_version bigint;
DECLARE latest_event_id bigint;
DECLARE source_kind text;
DECLARE source_id bigint;
DECLARE source_status text;
BEGIN
 IF p_actor_token='11111111-1111-4111-8111-111111111111'::uuid THEN NULL;
 ELSIF p_actor_token='33333333-3333-4333-8333-333333333333'::uuid THEN NULL;
 ELSE RAISE EXCEPTION 'QA_SYNTHETIC_ADMIN_PERMISSION_DENIED'; END IF;
 IF p_target_id<>2 OR p_status NOT IN ('readonly','disabled','active')
    OR p_effective_date IS NULL OR p_expected IS NULL
    OR p_expected_revision IS NULL OR length(p_expected_revision)<>32 THEN
   RAISE EXCEPTION 'QA_BAD_ARGS';
 END IF;
 SELECT revision INTO current_version
 FROM public.qa_two_admin_shared_revision WHERE id=1 FOR UPDATE;
 IF lpad(to_hex(current_version),32,'0')<>p_expected_revision THEN
   RAISE EXCEPTION 'STALE_PERSONNEL_RESTORE_REVISION';
 END IF;
 SELECT id,account_status INTO latest_event_id,source_status
 FROM public.qa_two_admin_account_events WHERE employee_id=2
 AND effective_date<=p_effective_date ORDER BY effective_date DESC,created_at DESC,id DESC LIMIT 1;
 IF latest_event_id IS NULL THEN
   source_kind:='assignment';source_id:=2;source_status:='active';
 ELSE
   source_kind:='event';source_id:=latest_event_id;
 END IF;
 IF p_expected->>'kind' IS DISTINCT FROM source_kind
    OR (p_expected->>'id')::bigint IS DISTINCT FROM source_id
    OR p_expected->>'status' IS DISTINCT FROM source_status THEN
   RAISE EXCEPTION 'STALE_PERSONNEL_ACCOUNT';
 END IF;
 INSERT INTO public.qa_two_admin_account_events (
   employee_id,account_status,effective_date,note,created_by
 ) VALUES (2,p_status,p_effective_date,p_note,
   CASE WHEN p_actor_token='11111111-1111-4111-8111-111111111111'::uuid THEN 1 ELSE 3 END);
 UPDATE public.qa_two_admin_shared_revision
 SET revision=revision+1,target_status=p_status WHERE id=1;
 RETURN true;
END $QA$;
COMMIT;
