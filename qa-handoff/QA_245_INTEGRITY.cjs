const sha=b=>crypto.createHash('sha256').update(b).digest('hex');
assert.strictEqual(sha(before),'9bfce02ca8be15ae1a59eebec2d3b05d1563784719ebec6308b7537e8fb9d9ab');
assert.strictEqual(before.length,1168824);
assert.strictEqual(sha(after),'2c673e4ac3d1a034394ce7d66180bfafe86090ab2aefbea1210d7da5191d3621');
