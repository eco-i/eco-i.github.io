'use strict';
const fs=require('fs'),assert=require('assert'),crypto=require('crypto'),vm=require('vm'),cp=require('child_process');
const beforePath='qa-handoff/index.before-2-8-252.html',afterPath='qa-handoff/index.working-2-8-252.html';
const before=fs.readFileSync(beforePath),after=fs.readFileSync(afterPath),text=after.toString('utf8');
const hash=x=>crypto.createHash('sha256').update(x).digest('hex');
const oldSha='90616051815b531adb615ba23005ad504ffb6898ffe5b6b19c3de9b147766c4e';
const newSha='32379ce57e0d5dac03686b82fa4b2c78c9427473cb1d35dda47dc41fce250aeb';
assert.strictEqual(hash(before),oldSha,'Official 250→251 baseline changed');
assert.strictEqual(before.length,1173752,'Original byte length mismatch');
assert.strictEqual(hash(after),newSha,'251 candidate SHA drift');
assert.strictEqual(after.length,1174027,'252 candidate byte length drift');
const scripts=[...text.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/gi)].map(m=>m[1]).filter(s=>s.trim());
assert(scripts.length===2,'Unexpected inline JS script count: '+scripts.length);
for(const script of scripts)new vm.Script(script);
const bodyBeforeJs=text.slice(0,text.indexOf('<script async src='));
const ids=[...bodyBeforeJs.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);
assert.strictEqual(new Set(ids).size,ids.length,'Duplicate DOM ID');
assert.strictEqual(ids.length,457,'Static DOM ID count drift');
assert(text.includes("ver20260927-0944"),'Version changed');
assert(text.includes("PC_SHARED_AUTHORITY_HISTORY_KEY='staffAttendance_pcSharedAuthorityHistory_v1'"),'Missing historical remembered-scope authority');
assert(text.includes("if(sharedToken===token&&storageGet(sessionStorage,SESSION_KEY)===token&&storageGet(localStorage,PC_REMEMBER_KEY)==='1')"),'Cold-bootstrap scope proof missing');
assert(text.includes("if(!storageSet(sessionStorage,PC_SHARED_AUTHORITY_HISTORY_KEY,token)){"),'Fail-closed scope-history write handling missing');
assert(text.includes("storageRemove(sessionStorage,ADMIN_UNLOCK_KEY);\n      storageRemove(sessionStorage,SESSION_KEY);"),'Stale tab credential purge missing');
assert(text.includes("storedSessionTombstoned(snapshot.current)||pcSharedAuthorityRevoked(snapshot.current)"),'Missing post-dialog revocation check');
assert(text.includes("tabToken===current&&!sessionIsPersistent(current))return {current,mode:'tab'}"),'Native dialogs still misclassify remembered dual scope');
const diff=cp.spawnSync('git',['diff','--no-index','--unified=0','--',beforePath,afterPath],{encoding:'utf8',maxBuffer:10*1024*1024});
assert.strictEqual(diff.status,1,'Expected source change diff');
const hunks=(diff.stdout.match(/^@@/gm)||[]).length;
const fileLines=diff.stdout.split('\n').filter(x=>x[0]==='+'||x[0]==='-').filter(x=>!x.startsWith('+++')&&!x.startsWith('---'));
assert(hunks>=1&&hunks<=12,'Unexpectedly broad diff hunks: '+hunks);
assert(fileLines.length<=24,'Unexpectedly broad source modifications: '+fileLines.length);
const removed=text.replace(/(\bconst proceed=confirm\((?:.|\n)*?\);)markNativeDialogReturn\(\);/g,'$1');
assert.strictEqual(removed,before.toString('utf8'),'Only eleven native confirmation marks may differ');
assert.strictEqual((text.match(/markNativeDialogReturn\(\);/g)||[]).length,13,'Expect original two + eleven added marks');
const guardedConfirmations=[...text.matchAll(/\bconst proceed=confirm\((?:.|\n)*?\);markNativeDialogReturn\(\);/g)];
assert.strictEqual(guardedConfirmations.length,11,'Each of eleven confirm exits must mark settlement');
for(const item of guardedConfirmations){
  assert(text.slice(item.index-530,item.index).includes('fingerprintBlockingPromptSessionChanged(promptSession)'),'Missing pre-dialog ownership check');
  assert(text.slice(item.index+item[0].length,item.index+item[0].length+390).includes('fingerprintBlockingPromptSessionChanged(promptSession)'),'Missing post-dialog ownership check');
}
console.log('QA252_INTEGRITY_PASS',JSON.stringify({oldSha,newSha,oldBytes:before.length,newBytes:after.length,scripts:scripts.length,uniqueDomIds:ids.length,sourceHunks:hunks,changedLines:fileLines.length,version:'ver20260927-0944'}));
