'use strict';
const fs=require('fs'),assert=require('assert'),crypto=require('crypto'),vm=require('vm'),cp=require('child_process');
const beforePath='qa-handoff/index.before-2-8-249.html',afterPath='qa-handoff/index.working-2-8-249.html';
const before=fs.readFileSync(beforePath),after=fs.readFileSync(afterPath),text=after.toString('utf8');
const hash=x=>crypto.createHash('sha256').update(x).digest('hex');
const oldSha='9ac74340a527a35f1f971b4a391417dfe395f2c4714a1cb66b03562ecf85a6c0';
const newSha='f7aaa89069348dae7ca267cec86b75b9bfe90b59465c77f223920936d7827d8a';
assert.strictEqual(hash(before),oldSha,'Official 248→249 baseline changed');
assert.strictEqual(before.length,1171231,'Original byte length mismatch');
assert.strictEqual(hash(after),newSha,'249 candidate SHA drift');
assert.strictEqual(after.length,1172508,'249 candidate byte length drift');
const scripts=[...text.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/gi)].map(m=>m[1]).filter(s=>s.trim());
assert(scripts.length===2,'Unexpected inline JS script count: '+scripts.length);
for(const script of scripts)new vm.Script(script);
const ids=[...text.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);
assert.strictEqual(new Set(ids).size,ids.length,'Duplicate DOM ID');
assert.strictEqual(ids.length,457,'Static DOM ID count drift');
assert(text.includes("ver20260927-0944"),'Version changed');
assert(text.includes("PC_SHARED_AUTHORITY_HISTORY_KEY='staffAttendance_pcSharedAuthorityHistory_v1'"),'Missing historical remembered-scope authority');
assert(text.includes("storedSessionTombstoned(snapshot.current)||pcSharedAuthorityRevoked(snapshot.current)"),'Missing post-dialog revocation check');
assert(text.includes("tabToken===current&&!sessionIsPersistent(current))return {current,mode:'tab'}"),'Native dialogs still misclassify remembered dual scope');
const diff=cp.spawnSync('git',['diff','--no-index','--unified=0','--',beforePath,afterPath],{encoding:'utf8',maxBuffer:10*1024*1024});
assert.strictEqual(diff.status,1,'Expected source change diff');
const hunks=(diff.stdout.match(/^@@/gm)||[]).length;
const fileLines=diff.stdout.split('\n').filter(x=>x[0]==='+'||x[0]==='-').filter(x=>!x.startsWith('+++')&&!x.startsWith('---'));
assert(hunks>=4&&hunks<=14,'Unexpectedly broad diff hunks: '+hunks);
assert(fileLines.length<100,'Unexpectedly broad source modifications: '+fileLines.length);
console.log('QA249_INTEGRITY_PASS',JSON.stringify({oldSha,newSha,oldBytes:before.length,newBytes:after.length,scripts:scripts.length,uniqueDomIds:ids.length,sourceHunks:hunks,changedLines:fileLines.length,version:'ver20260927-0944'}));
